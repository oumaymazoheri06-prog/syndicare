const normalizeForLookup = (value) =>
    String(value)
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/\s+/g, ' ')
        .trim()
        .toLowerCase();

const lookup = new Map(
    Object.entries(arabicTranslations).map(([key, value]) => [
        normalizeForLookup(key),
        value,
    ]),
);

const withTranslatedTerm = (prefix, term) => {
    const translated = translateText(term, 'ar');

    return `${prefix} ${translated === term ? term : translated}`;
};


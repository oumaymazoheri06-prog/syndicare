export function normalizeLocale(locale) {
    return languageOptions.some((language) => language.code === locale)
        ? locale
        : 'fr';
}

export function localeDirection(locale) {
    return (
        languageOptions.find((language) => language.code === locale)
            ?.direction ?? 'ltr'
    );
}

export function getStoredLocale() {
    if (typeof window === 'undefined') {
        return 'fr';
    }

    return normalizeLocale(window.localStorage.getItem('locale') || 'fr');
}

export function translateText(value, locale = 'fr') {
    if (locale !== 'ar' || value === null || value === undefined) {
        return value;
    }

    const text = String(value);
    const leading = text.match(/^\s*/)?.[0] ?? '';
    const trailing = text.match(/\s*$/)?.[0] ?? '';
    const compact = text.trim().replace(/\s+/g, ' ');

    if (!compact) {
        return value;
    }

    const exact = lookup.get(normalizeForLookup(compact));

    if (exact) {
        return `${leading}${exact}${trailing}`;
    }

    for (const pattern of arabicPatterns) {
        const match = compact.match(pattern.regex);

        if (match) {
            return `${leading}${pattern.replace(match)}${trailing}`;
        }
    }

    return value;
}
